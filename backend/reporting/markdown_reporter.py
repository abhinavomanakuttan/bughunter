"""
BugHunter — Markdown Reporter
Generates a clean Markdown report from scan results.
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def generate_markdown_report(
    scan: dict[str, Any],
    findings: list[dict[str, Any]],
    output_path: Path | None = None,
) -> str:
    """
    Generate a Markdown report from a scan and its findings.

    Args:
        scan: Scan record from database
        findings: List of findings from database
        output_path: Optional path to write the markdown file

    Returns:
        Markdown report as string
    """
    url = scan.get("url", "unknown")
    scan_id = scan.get("id", "unknown")
    status = scan.get("status", "unknown")
    pages = scan.get("pages_crawled", 0)
    findings_count = scan.get("findings_count", 0)
    tests_total = scan.get("tests_total", 0)
    tests_passed = scan.get("tests_passed", 0)
    tests_failed = scan.get("tests_failed", 0)
    wcag_score = scan.get("wcag_score", 100.0)
    started_at = scan.get("started_at", "")
    finished_at = scan.get("finished_at", "")

    # Calculate pass rate
    pass_rate = (tests_passed / tests_total * 100) if tests_total > 0 else 0.0

    # Group findings by severity
    by_severity: dict[str, list] = {
        "CRITICAL": [],
        "HIGH": [],
        "MEDIUM": [],
        "LOW": [],
    }
    for f in findings:
        sev = f.get("severity", "MEDIUM")
        by_severity.setdefault(sev, []).append(f)

    lines = [
        f"# BugHunter Scan Report",
        f"",
        f"**Scan ID**: `{scan_id}`  ",
        f"**Target URL**: {url}  ",
        f"**Status**: {status}  ",
        f"**Started**: {started_at}  ",
        f"**Finished**: {finished_at}  ",
        f"",
        f"---",
        f"",
        f"## Summary",
        f"",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Pages Crawled | {pages} |",
        f"| Total Findings | {findings_count} |",
        f"| Tests Run | {tests_total} |",
        f"| Tests Passed | {tests_passed} |",
        f"| Tests Failed | {tests_failed} |",
        f"| Pass Rate | {pass_rate:.1f}% |",
        f"| WCAG Score | {wcag_score:.1f}/100 |",
        f"| Critical Issues | {len(by_severity['CRITICAL'])} |",
        f"| High Issues | {len(by_severity['HIGH'])} |",
        f"| Medium Issues | {len(by_severity['MEDIUM'])} |",
        f"| Low Issues | {len(by_severity['LOW'])} |",
        f"",
        f"---",
        f"",
        f"## Findings by Severity",
        f"",
    ]

    for severity in ["CRITICAL", "HIGH", "MEDIUM", "LOW"]:
        sev_findings = by_severity.get(severity, [])
        if not sev_findings:
            continue

        severity_emoji = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🟢"}.get(severity, "⚪")
        lines.append(f"### {severity_emoji} {severity} ({len(sev_findings)})")
        lines.append("")

        for f in sev_findings:
            title = f.get("title", "Untitled")
            description = f.get("description", "")
            url_context = f.get("url", "")
            selector = f.get("selector", "")
            finding_type = f.get("finding_type", "")
            fix = f.get("recommended_fix", "")
            steps = f.get("reproduction_steps", [])

            lines.append(f"#### {title}")
            lines.append(f"")
            lines.append(f"- **Type**: `{finding_type}`")
            if url_context:
                lines.append(f"- **URL**: {url_context}")
            if selector:
                lines.append(f"- **Selector**: `{selector}`")
            if description:
                lines.append(f"- **Description**: {description}")
            if fix:
                lines.append(f"- **Recommended Fix**: {fix}")
            if steps:
                lines.append(f"- **Reproduction Steps**:")
                for step in steps:
                    lines.append(f"  1. {step}")
            lines.append("")

    lines.extend([
        "---",
        "",
        f"*Generated by BugHunter — {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}*",
    ])

    content = "\n".join(lines)

    if output_path:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(content, encoding="utf-8")
        logger.info("Markdown report saved: %s", output_path)

    return content
